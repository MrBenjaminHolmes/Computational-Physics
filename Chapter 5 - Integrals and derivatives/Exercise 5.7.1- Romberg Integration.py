import numpy as np

def f(x):
    return np.sin(np.sqrt(100*x))**2
N=1
a=0.0
b=1.0
h=(b-a)/N
e=1000
i=0
size=15
R=np.zeros([size,size],dtype=float)
while abs(e) > 1e-6:
    h=(b-a)/N

    s=0.5*f(a) + 0.5*f(b)
    for k in range(1,N):
        s+=f(a+k*h)
    R[i,0] = h*s
    for m in range(1,i+1):
        R[i,m] = R[i,m-1] + (R[i,m-1]-R[i-1,m-1])/(4**m-1)
        e = (R[i,m-1]-R[i-1,m-1])/(4**m-1)
    N*=2
    i+=1
    
for i in range(size):
    if np.any(R[i, :] != 0):
        print(*R[i, R[i, :] != 0])

